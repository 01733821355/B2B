object PdfReportGenerator {

  /**
   * Generates a formal, printable PDF Performance Summary Report
   */
  fun generatePdfReport(
    context: Context,
    files: List<CustomerFileEntity>,
    currentUser: UserEntity,
    periodLabel: String,
    customAppName: String
  ): File {
    val document = PdfDocument()
    val pageWidth = 595 // Standard A4 points (72 dpi)
    val pageHeight = 842
    val pageInfo = PdfDocument.PageInfo.Builder(pageWidth, pageHeight, 1).create()
    val page = document.startPage(pageInfo)
    val canvas: Canvas = page.canvas

    val textPaint = Paint().apply {
      isAntiAlias = true
      textSize = 10f
      color = Color.DKGRAY
    }

    val headerPaint = Paint().apply {
      isAntiAlias = true
      textSize = 16f
      typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
      color = Color.rgb(10, 25, 47) // EblNavyDark
    }

    val subHeaderPaint = Paint().apply {
      isAntiAlias = true
      textSize = 10f
      typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
      color = Color.rgb(30, 58, 138)
    }

    val tableHeaderPaint = Paint().apply {
      isAntiAlias = true
      textSize = 9f
      typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
      color = Color.WHITE
    }

    val bgHeaderPaint = Paint().apply {
      color = Color.rgb(10, 25, 47)
    }

    val alternateRowPaint = Paint().apply {
      color = Color.rgb(245, 247, 250)
    }

    val borderPaint = Paint().apply {
      color = Color.LTGRAY
      strokeWidth = 0.5f
      style = Paint.Style.STROKE
    }

    var y = 40f

    // 1. Header Banner
    canvas.drawText(customAppName.ifBlank { "RM File Management Suite" }, 30f, y, headerPaint)
    y += 18f
    canvas.drawText("EXECUTIVE PERFORMANCE SUMMARY REPORT", 30f, y, subHeaderPaint)
    y += 14f

    textPaint.textSize = 8.5f
    val generatedTime = DateUtils.formatDateTime(DateUtils.currentDhakaMillis())
    canvas.drawText("Generated by: ${currentUser.name} (${currentUser.role} ${currentUser.rmCode}) • Timezone: Asia/Dhaka (GMT+6)", 30f, y, textPaint)
    y += 12f
    canvas.drawText("Reporting Period: $periodLabel • Generated at: $generatedTime", 30f, y, textPaint)
    y += 16f

    // 2. Summary KPI Box
    val totalCount = files.size
    val approvedCount = files.count { it.applicationStatus.equals("Approved", true) }
    val submittedCount = files.count { it.applicationStatus.equals("Submitted", true) }
    val collectedCount = files.count { it.applicationStatus.equals("Collected", true) }
    val declinedCount = files.count { it.applicationStatus.equals("Declined", true) }

    val kpiBoxPaint = Paint().apply {
      color = Color.rgb(240, 244, 248)
    }
    canvas.drawRect(30f, y, pageWidth - 30f, y + 42f, kpiBoxPaint)
    canvas.drawRect(30f, y, pageWidth - 30f, y + 42f, borderPaint)

    val kpiTextPaint = Paint().apply {
      isAntiAlias = true
      textSize = 9f
      typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
      color = Color.rgb(15, 23, 42)
    }

    canvas.drawText("TOTAL FILES: $totalCount", 45f, y + 16f, kpiTextPaint)
    canvas.drawText("APPROVED: $approvedCount", 160f, y + 16f, kpiTextPaint)
    canvas.drawText("SUBMITTED: $submittedCount", 270f, y + 16f, kpiTextPaint)
    canvas.drawText("COLLECTED: $collectedCount", 380f, y + 16f, kpiTextPaint)
    canvas.drawText("DECLINED: $declinedCount", 490f, y + 16f, kpiTextPaint)

    val kpiSubText = Paint().apply {
      isAntiAlias = true
      textSize = 7.5f
      color = Color.GRAY
    }
    val approvalRatio = if (totalCount > 0) (approvedCount * 100 / totalCount) else 0
    canvas.drawText("Overall Approval Conversion Rate: $approvalRatio% • Confidential Internal Banking Records", 45f, y + 32f, kpiSubText)

    y += 56f

    // 3. Table Column Headers
    val colX = floatArrayOf(30f, 100f, 210f, 290f, 370f, 435f, 480f, pageWidth - 30f)
    canvas.drawRect(30f, y, pageWidth - 30f, y + 18f, bgHeaderPaint)

    canvas.drawText("CC-Number", colX[0] + 4f, y + 12f, tableHeaderPaint)
    canvas.drawText("Customer Name", colX[1] + 4f, y + 12f, tableHeaderPaint)
    canvas.drawText("Mobile", colX[2] + 4f, y + 12f, tableHeaderPaint)
    canvas.drawText("Product", colX[3] + 4f, y + 12f, tableHeaderPaint)
    canvas.drawText("Status", colX[4] + 4f, y + 12f, tableHeaderPaint)
    canvas.drawText("RM", colX[5] + 4f, y + 12f, tableHeaderPaint)
    canvas.drawText("Date", colX[6] + 4f, y + 12f, tableHeaderPaint)

    y += 18f

    // 4. Data Rows
    val rowPaint = Paint().apply {
      isAntiAlias = true
      textSize = 8f
      color = Color.BLACK
    }

    var rowIndex = 0
    for (f in files.take(35)) { // Max 35 rows per first page
      if (rowIndex % 2 == 1) {
        canvas.drawRect(30f, y, pageWidth - 30f, y + 16f, alternateRowPaint)
      }
      canvas.drawLine(30f, y + 16f, pageWidth - 30f, y + 16f, borderPaint)

      val ccText = f.ccNumber.ifBlank { f.fileId }
      canvas.drawText(ccText.take(12), colX[0] + 4f, y + 11f, rowPaint)
      canvas.drawText(f.customerName.take(18), colX[1] + 4f, y + 11f, rowPaint)
      canvas.drawText(f.mobile.take(13), colX[2] + 4f, y + 11f, rowPaint)
      canvas.drawText(f.productType.take(12), colX[3] + 4f, y + 11f, rowPaint)

      // Status with specific color indicator
      val statusPaint = Paint(rowPaint).apply {
        typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        color = when (f.applicationStatus) {
          "Approved" -> Color.rgb(21, 128, 61)
          "Submitted" -> Color.rgb(29, 78, 216)
          "Declined" -> Color.rgb(185, 28, 28)
          else -> Color.DKGRAY
        }
      }
      canvas.drawText(f.applicationStatus.take(10), colX[4] + 4f, y + 11f, statusPaint)
      canvas.drawText(f.assignedRmCode.take(6), colX[5] + 4f, y + 11f, rowPaint)
      canvas.drawText(DateUtils.formatDateOnly(f.updatedAt), colX[6] + 4f, y + 11f, rowPaint)

      y += 16f
      rowIndex++
    }

    // Footer Security Notice
    y = pageHeight - 30f
    val footerPaint = Paint().apply {
      isAntiAlias = true
      textSize = 7.5f
      color = Color.GRAY
    }
    canvas.drawText("CONFIDENTIAL DOCUMENT — STRICTLY FOR INTERNAL BANKING USE — NOT FOR PUBLIC DISSEMINATION", 30f, y, footerPaint)
    canvas.drawText("Page 1 of 1", pageWidth - 80f, y, footerPaint)

    document.finishPage(page)

    // Save PDF to cache directory
    val reportsDir = File(context.cacheDir, "reports").apply { mkdirs() }
    val reportFile = File(reportsDir, "RM_Report_${System.currentTimeMillis()}.pdf")
    FileOutputStream(reportFile).use { out ->
      document.writeTo(out)
    }
    document.close()
    return reportFile
  }

  /**
   * Generates a formal, printable PDF Event Result & Performance Report for Admin and Mentor
   */
  fun generateEventResultPdfReport(
    context: Context,
    event: TeamEventEntity,
    responses: List<EventResponseEntity>,
    currentUser: UserEntity,
    customAppName: String
  ): File {
    val document = PdfDocument()
    val pageWidth = 595 // Standard A4 points (72 dpi)
    val pageHeight = 842
    val pageInfo = PdfDocument.PageInfo.Builder(pageWidth, pageHeight, 1).create()
    val page = document.startPage(pageInfo)
    val canvas: Canvas = page.canvas

    val textPaint = Paint().apply {
      isAntiAlias = true
      textSize = 9f
      color = Color.DKGRAY
    }

    val headerPaint = Paint().apply {
      isAntiAlias = true
      textSize = 15f
      typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
      color = Color.rgb(10, 25, 47)
    }

    val subHeaderPaint = Paint().apply {
      isAntiAlias = true
      textSize = 11f
      typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
      color = Color.rgb(30, 58, 138)
    }

    val tableHeaderPaint = Paint().apply {
      isAntiAlias = true
      textSize = 8.5f
      typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
      color = Color.WHITE
    }

    val bgHeaderPaint = Paint().apply {
      color = Color.rgb(10, 25, 47)
    }

    val alternateRowPaint = Paint().apply {
      color = Color.rgb(245, 247, 250)
    }

    val borderPaint = Paint().apply {
      color = Color.LTGRAY
      strokeWidth = 0.5f
      style = Paint.Style.STROKE
    }

    var y = 35f

    // 1. Header Banner
    canvas.drawText(customAppName.ifBlank { "RM File Management Suite" }, 30f, y, headerPaint)
    y += 18f
    canvas.drawText("EVENT RESULT & SUBMISSIONS REPORT", 30f, y, subHeaderPaint)
    y += 14f

    val reportTime = DateUtils.formatDateTime(DateUtils.currentDhakaMillis())
    canvas.drawText("Report Generated: $reportTime (Dhaka Time)", 30f, y, textPaint)
    canvas.drawText("Authorized Officer: ${currentUser.name} (${currentUser.role} - ${currentUser.rmCode})", 300f, y, textPaint)
    y += 14f

    // Divider line
    canvas.drawLine(30f, y, pageWidth - 30f, y, borderPaint)
    y += 14f

    // 2. Event Overview Card Box
    val cardPaint = Paint().apply {
      color = Color.rgb(238, 242, 255)
      style = Paint.Style.FILL
    }
    canvas.drawRoundRect(30f, y, pageWidth - 30f, y + 62f, 6f, 6f, cardPaint)
    canvas.drawRoundRect(30f, y, pageWidth - 30f, y + 62f, 6f, 6f, borderPaint)

    val labelPaint = Paint().apply {
      isAntiAlias = true
      textSize = 9.5f
      typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
      color = Color.rgb(30, 58, 138)
    }
    val valuePaint = Paint().apply {
      isAntiAlias = true
      textSize = 9f
      color = Color.rgb(30, 41, 59)
    }

    canvas.drawText("Event Title: ${event.title}", 40f, y + 16f, labelPaint)
    canvas.drawText("Event ID: ${event.eventId}", 40f, y + 32f, valuePaint)
    canvas.drawText("Target Date: ${event.targetDate.ifBlank { "N/A" }}", 40f, y + 48f, valuePaint)

    val totalFiles = responses.sumOf { it.filesCount }
    canvas.drawText("Created By: ${event.creatorName} (${event.creatorRmCode})", 280f, y + 16f, valuePaint)
    canvas.drawText("Total Submitting RMs: ${responses.size}", 280f, y + 32f, labelPaint)
    canvas.drawText("Total Achieved Files: $totalFiles Files", 280f, y + 48f, labelPaint)
    y += 76f

    // 3. Submissions Table Header
    canvas.drawRect(30f, y, pageWidth - 30f, y + 22f, bgHeaderPaint)
    canvas.drawText("#", 35f, y + 14f, tableHeaderPaint)
    canvas.drawText("RM Name (Code)", 55f, y + 14f, tableHeaderPaint)
    canvas.drawText("Files", 175f, y + 14f, tableHeaderPaint)
    canvas.drawText("Target Date", 215f, y + 14f, tableHeaderPaint)
    canvas.drawText("Location", 285f, y + 14f, tableHeaderPaint)
    canvas.drawText("Customers (Name & Phone)", 370f, y + 14f, tableHeaderPaint)
    canvas.drawText("Remarks", 495f, y + 14f, tableHeaderPaint)
    y += 22f

    // 4. Data Rows
    if (responses.isEmpty()) {
      canvas.drawText("No RM submissions received yet for this event.", 40f, y + 20f, textPaint)
      y += 35f
    } else {
      responses.forEachIndexed { index, resp ->
        if (y > pageHeight - 70f) return@forEachIndexed

        if (index % 2 == 1) {
          canvas.drawRect(30f, y, pageWidth - 30f, y + 26f, alternateRowPaint)
        }
        canvas.drawRect(30f, y, pageWidth - 30f, y + 26f, borderPaint)

        // Parse customer details preview
        var custSummary = ""
        if (resp.customerEntriesJson.isNotBlank()) {
          try {
            val arr = org.json.JSONArray(resp.customerEntriesJson)
            val names = mutableListOf<String>()
            for (ci in 0 until arr.length()) {
              val co = arr.getJSONObject(ci)
              val n = co.optString("name")
              val m = co.optString("mobile")
              names.add(if (m.isNotBlank()) "$n ($m)" else n)
            }
            custSummary = names.take(2).joinToString(", ")
            if (names.size > 2) custSummary += " +${names.size - 2}"
          } catch (_: Exception) {}
        }
        if (custSummary.isBlank()) custSummary = "-"

        canvas.drawText("${index + 1}", 35f, y + 16f, textPaint)
        val rmDisplay = "${resp.rmName.take(18)} (${resp.rmCode})"
        canvas.drawText(rmDisplay.take(22), 55f, y + 16f, textPaint)
        canvas.drawText("${resp.filesCount}", 180f, y + 16f, textPaint)
        canvas.drawText(resp.requestedDate.take(12).ifBlank { "-" }, 215f, y + 16f, textPaint)
        canvas.drawText(resp.location.take(14).ifBlank { "-" }, 285f, y + 16f, textPaint)
        canvas.drawText(custSummary.take(22), 370f, y + 16f, textPaint)
        canvas.drawText(resp.remarks.take(16).ifBlank { "-" }, 495f, y + 16f, textPaint)

        y += 26f
      }
    }

    // 5. Performance Summary Box at Bottom
    y += 12f
    if (y < pageHeight - 80f) {
      canvas.drawLine(30f, y, pageWidth - 30f, y, borderPaint)
      y += 16f
      val boldSummary = Paint().apply {
        isAntiAlias = true
        textSize = 9.5f
        typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        color = Color.rgb(10, 25, 47)
      }
      canvas.drawText("Summary Statistics:  Participating RMs: ${responses.size}  •  Total Files Achieved: $totalFiles Files", 35f, y, boldSummary)
      y += 14f
      canvas.drawText("Status: ${event.status}  •  Event Description: ${event.description.take(70)}", 35f, y, textPaint)
    }

    // Footer Security Notice
    y = pageHeight - 30f
    val footerPaint = Paint().apply {
      isAntiAlias = true
      textSize = 7.5f
      color = Color.GRAY
    }
    canvas.drawText("CONFIDENTIAL DOCUMENT — STRICTLY FOR INTERNAL BANKING USE — NOT FOR PUBLIC DISSEMINATION", 30f, y, footerPaint)
    canvas.drawText("Page 1 of 1", pageWidth - 80f, y, footerPaint)

    document.finishPage(page)

    // Save PDF to cache directory
    val reportsDir = File(context.cacheDir, "reports").apply { mkdirs() }
    val reportFile = File(reportsDir, "Event_Report_${event.eventId}_${System.currentTimeMillis()}.pdf")
    FileOutputStream(reportFile).use { out ->
      document.writeTo(out)
    }
    document.close()
    return reportFile
  }

  /**
   * Opens or shares the generated PDF file via system Android intents
   */
  fun shareOrViewPdf(context: Context, pdfFile: File) {
    val uri: Uri = try {
      FileProvider.getUriForFile(
        context,
        "${context.packageName}.fileprovider",
        pdfFile
      )
    } catch (e: Exception) {
      Uri.fromFile(pdfFile)
    }

    // Also copy to Downloads so user has a permanent offline copy on device
    savePdfToDownloads(context, pdfFile, pdfFile.name)

    // Primary: Open directly in PDF viewer (Google Drive PDF, Adobe, Chrome)
    val viewIntent = Intent(Intent.ACTION_VIEW).apply {
      setDataAndType(uri, "application/pdf")
      addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
      addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
    }

    try {
      val chooser = Intent.createChooser(viewIntent, "Open PDF Report with").apply {
        addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
      }
      context.startActivity(chooser)
    } catch (_: Exception) {
      // Fallback to ACTION_SEND if no direct PDF viewer is available
      try {
        val sendIntent = Intent(Intent.ACTION_SEND).apply {
          type = "application/pdf"
          putExtra(Intent.EXTRA_STREAM, uri)
          putExtra(Intent.EXTRA_SUBJECT, "Performance / Event Summary Report (PDF)")
          addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
          addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        }
        context.startActivity(Intent.createChooser(sendIntent, "Open or Share PDF Report").apply {
          addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        })
      } catch (e2: Exception) {
        android.widget.Toast.makeText(context, "PDF saved to Downloads folder: ${pdfFile.name}", android.widget.Toast.LENGTH_LONG).show()
      }
    }
  }

  /**
   * Saves a permanent copy of the PDF into device Downloads storage
   */
  fun savePdfToDownloads(context: Context, pdfFile: File, displayName: String): Uri? {
    try {
      if (android.os.Build.VERSION.SDK_INT >= android.os.Build.VERSION_CODES.Q) {
        val values = android.content.ContentValues().apply {
          put(android.provider.MediaStore.MediaColumns.DISPLAY_NAME, displayName)
          put(android.provider.MediaStore.MediaColumns.MIME_TYPE, "application/pdf")
          put(android.provider.MediaStore.MediaColumns.RELATIVE_PATH, android.os.Environment.DIRECTORY_DOWNLOADS)
        }
        val resolver = context.contentResolver
        val uri = resolver.insert(android.provider.MediaStore.Downloads.EXTERNAL_CONTENT_URI, values)
        if (uri != null) {
          resolver.openOutputStream(uri)?.use { out ->
            pdfFile.inputStream().use { input ->
              input.copyTo(out)
            }
          }
          return uri
        }
      } else {
        @Suppress("DEPRECATION")
        val downloadsDir = android.os.Environment.getExternalStoragePublicDirectory(android.os.Environment.DIRECTORY_DOWNLOADS)
        downloadsDir.mkdirs()
        val destFile = File(downloadsDir, displayName)
        pdfFile.copyTo(destFile, overwrite = true)
        return Uri.fromFile(destFile)
      }
    } catch (_: Exception) {}
    return null
  }
